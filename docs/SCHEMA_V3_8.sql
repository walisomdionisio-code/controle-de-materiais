create table if not exists public.controle_materiais (
  id bigint generated by default as identity primary key,
  nome text not null,
  data_rito date not null,
  status text not null default 'Planejado'
    check (status in ('Planejado','Em produção','Validação','Finalizado')),
  responsavel text not null default 'Walisom',
  validador text not null default 'Diretora',
  link_sharepoint text,
  observacao text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  prioridade text not null default 'Importante / não urgente',
  natureza text not null default 'Rito',
  recorrencia text not null default 'Sob demanda',
  origem_recorrencia text unique,
  criado_por text not null default 'Walisom',
  requer_validacao boolean not null default true
);

create table if not exists public.controle_materiais_atividade (
  id bigint generated by default as identity primary key,
  material_id bigint,
  usuario text not null,
  acao text not null,
  detalhe text,
  created_at timestamptz not null default now()
);

alter table public.controle_materiais_atividade
  drop constraint if exists controle_materiais_atividade_material_id_fkey;

alter table public.controle_materiais_atividade
  add constraint controle_materiais_atividade_material_id_fkey
  foreign key (material_id)
  references public.controle_materiais(id)
  on delete set null;

create table if not exists public.controle_materiais_recorrencia_excecoes (
  id bigint generated by default as identity primary key,
  origem_recorrencia text not null unique,
  nome text,
  data_rito date,
  excluido_por text not null,
  created_at timestamptz not null default now()
);

alter table public.controle_materiais enable row level security;
alter table public.controle_materiais_atividade enable row level security;
alter table public.controle_materiais_recorrencia_excecoes enable row level security;

